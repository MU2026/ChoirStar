"""Extract SVG outlines from the pinned Bravura OTF (requires fonttools).

Usage: python scripts/extract-notation-glyphs.py /path/to/Bravura.otf
Source and license: docs/upstream.md. Output retains the SIL OFL license.
"""
import json
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

font = TTFont(sys.argv[1])
glyph_set = font.getGlyphSet()
cmap = font.getBestCmap()
codes = {
    "treble": 0xE050, "bass": 0xE062,
    "whole": 0xE0A2, "half": 0xE0A3, "black": 0xE0A4,
    "flat": 0xE260, "natural": 0xE261, "sharp": 0xE262,
    **{f"rest{i}": 0xE4E3 + i for i in range(7)},
    **{f"flag{i}{direction}": 0xE240 + (i - 1) * 2 + offset
       for i in range(1, 5) for direction, offset in [("Up", 0), ("Down", 1)]},
    **{f"digit{i}": 0xE080 + i for i in range(10)},
}
result = {}
for name, code in codes.items():
    glyph = glyph_set[cmap[code]]
    pen = SVGPathPen(glyph_set)
    glyph.draw(pen)
    bounds = BoundsPen(glyph_set)
    glyph.draw(bounds)
    result[name] = {"path": pen.getCommands(), "bounds": bounds.bounds,
                    "advance": glyph.width}
output = Path(__file__).resolve().parents[1] / "src/vendor/bravura/glyphs.ts"
output.write_text(
    '// Generated by scripts/extract-notation-glyphs.py. Do not edit.\n'
    '// Bravura outlines © 2026 Steinberg Media Technologies GmbH.\n'
    '// SIL OFL 1.1; see public/licenses/Bravura-OFL.txt and docs/upstream.md.\n'
    f'export const unitsPerEm = {font["head"].unitsPerEm};\n'
    'export const glyphs = ' + json.dumps(result, separators=(",", ":")) + ' as const;\n'
)
